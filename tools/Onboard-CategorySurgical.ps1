            $ra = az role assignment list --assignee $faPid --scope $dcrId --role 'Monitoring Metrics Publisher' -o json 2>$null | ConvertFrom-Json
            $haveRole = @($ra).Count -gt 0
        } catch { $haveRole = $false }
        if ($haveRole) {
            # Tuple already granted. Surface whether it is under the DETERMINISTIC name (a full re-deploy will be a
            # clean idempotent no-op) or a legacy RANDOM name (a full mainTemplate re-deploy would 409 RoleAssignmentExists
            # against it · Defect-1 drift). We do NOT delete/recreate here (avoid a momentary publish-permission gap on a
            # live DCR); the name only governs the FULL-deploy path, and this onboard's own ingest works under either name.
            $existingNames = @(@($ra) | ForEach-Object { [string]$_.name })
            if ($existingNames -contains $roleAssignmentName) {
                Write-Host "[Onboard-CategorySurgical] per-DCR Monitoring Metrics Publisher role already present on $dcrName under the deterministic name · skip (full re-deploy is a clean no-op)"
            } else {
                Write-Warning "[Onboard-CategorySurgical] per-DCR MMP role present on $dcrName but under name(s) [$($existingNames -join ', ')], NOT the deterministic '$roleAssignmentName'. The FA SAMI can publish (ingest is fine), but a FULL mainTemplate re-deploy would 409 RoleAssignmentExists (Defect-1). To converge: delete the legacy assignment then re-run -Apply (or let the targeted role path recreate it deterministically)."
            }
        } else {
            Write-Host "[Onboard-CategorySurgical] granting FA SAMI Monitoring Metrics Publisher on $dcrName (deterministic name $roleAssignmentName) ..."
            # --name pins the assignment to the template's guid() so a later full mainTemplate deploy is a same-name no-op.
            $grantOut = az role assignment create --assignee-object-id $faPid --assignee-principal-type ServicePrincipal --role 'Monitoring Metrics Publisher' --scope $dcrId --name $roleAssignmentName --output none 2>&1 | Out-String
            if ($LASTEXITCODE -ne 0 -and ($grantOut -notmatch 'RoleAssignmentExists')) { throw "[Onboard-CategorySurgical] per-DCR role grant FAILED (az exit $LASTEXITCODE): $grantOut" }
        }
    } else {
        Write-Warning "[Onboard-CategorySurgical] could not resolve dcrName/sub/FA-principalId · per-DCR role NOT ensured. Verify manually: the FA SAMI needs Monitoring Metrics Publisher on the DCR or ingest will 403 (silent 0 rows)."
