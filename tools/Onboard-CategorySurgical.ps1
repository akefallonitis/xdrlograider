    # ─── Recreate-on-schema-drift guard (BEFORE what-if · in-place LA table modify silently corrupts ingestion) ──
    # The table is deployed as a Microsoft.OperationalInsights/workspaces/tables ARM resource. On an EXISTING table an
    # ARM PUT does an IN-PLACE modify: LA updates the query-time schema (getschema reflects it) but the INGESTION-time
    # schema goes stale, so new rows silently DROP any column whose type changed (string→boolean is rejected outright)
    # or that was newly added (live-caught 2026-06-17 · Operations GetTenantContext typed cols green-but-null). A FRESH
    # table has a consistent ingest+query schema. Detect drift; DROP+RECREATE with -RecreateTableOnSchemaDrift, else
    # FAIL CLOSED (never silently in-place-modify into a stale schema). Table delete is cross-RG (the workspace RG).
    $wsParts = @($pWorkspaceResId -split '/')
    $wsRG    = $wsParts[4]
    $wsName  = $wsParts[-1]
    # EFFECTIVE schema via KQL getschema (NOT `table show` · the DECLARED schema DIVERGES from the effective/ingestion
    # schema after a failed in-place type change — `table show` optimistically reports the target type the ARM PUT
    # requested while getschema reports the actual stored type that governs ingestion · IsSuspended declared=boolean /
    # effective=string live-caught 2026-06-17). Resolve the workspace customerId for the LA query API.
    $wsCustomerId = az monitor log-analytics workspace show --ids $pWorkspaceResId --query customerId -o tsv 2>$null
    $liveCols = @(); $tableExists = $false
    if ($wsCustomerId) {
        $schemaRaw = az monitor log-analytics query --workspace $wsCustomerId --analytics-query "$tableName | getschema | project ColumnName, ColumnType" -o json 2>$null
        if ($LASTEXITCODE -eq 0 -and $schemaRaw) {
            $rows = @($schemaRaw | ConvertFrom-Json -Depth 30)
            if ($rows.Count -gt 0) { $tableExists = $true; $liveCols = @($rows | ForEach-Object { [pscustomobject]@{ name = $_.ColumnName; type = $_.ColumnType } }) }
        }
    } else {
        Write-Warning "[Onboard-CategorySurgical] could not resolve workspace customerId from '$pWorkspaceResId' · skipping the effective-schema drift check (an in-place type-change would silently fail · verify typed cols populate post-deploy)."
    }
    if ($tableExists) {
        $drift = @(Test-XdrTableColumnDrift -TargetCols $tableCols -LiveCols $liveCols)
        if ($drift.Count -gt 0) {
            Write-Host ""
            Write-Host "[Onboard-CategorySurgical] TABLE SCHEMA DRIFT · live '$tableName' differs from target in $($drift.Count) col(s):" -ForegroundColor Yellow
            $drift | Select-Object -First 60 | ForEach-Object { Write-Host "   ~ $_" -ForegroundColor Yellow }
            # Capture the NEW-column names from the SAME $drift list (entries shaped "ADD <name> (<type>)" · Test-XdrTableColumnDrift
            # line ~169) — these are exactly the cols subject to the DCR schema-propagation lag if we recreate. RETYPE entries are
            # EXCLUDED (those cols pre-exist, so they are not propagation-pending). No recompute — parsed from the diff just logged.
            $addedColumns = @($drift | Where-Object { $_ -like 'ADD *' } | ForEach-Object { ($_ -replace '^ADD\s+([^\s(]+).*$', '$1') })
            if (-not $RecreateTableOnSchemaDrift) {
                throw "[Onboard-CategorySurgical] FAIL CLOSED · live table '$tableName' schema drifts from target · an in-place ARM PUT does NOT reliably apply column type-changes/additions (LA updates the query-time schema but NOT the ingestion path → new rows silently drop the changed cols · live-caught 2026-06-17). Re-run with -RecreateTableOnSchemaDrift to DROP+RECREATE the table fresh (DESTRUCTIVE · drops existing rows in '$tableName' · re-poll repopulates · the proven cat-1 Exposure path)."
            }
            if (-not $Apply) {
                Write-Host "[Onboard-CategorySurgical] PLAN-ONLY · -RecreateTableOnSchemaDrift set · WOULD drop+recreate '$tableName' on -Apply (no mutation in plan mode)." -ForegroundColor Yellow
            } else {
                # DROP+recreate of a same-name table APPLIES THE NEW SCHEMA — live-proven 2026-06-20: a populated 50-col
                # Defender_SecureScore_CL was dropped with NO prior purge and the ARM recreate landed the full 65-col target
                # schema (NOT a 50-col soft-restore). The earlier "soft-restore blocks the retype" guard CONFLATED the REAL
                # in-place-ARM-PUT green-but-null (ADD-cols-WITHOUT-drop · still true · that is WHY we DROP rather than PUT)
                # with a drop+recreate "soft-restore" that does NOT happen on our _CL tables. So a NON-EMPTY table needs NO
                # purge to recreate fresh-typed. The old rows MAY linger as soft-restored DATA, but that is COSMETIC — the
                # windowed verifier (DeployedSinceUtc) excludes pre-deploy rows and the next poll re-emits fresh-typed.
                # -PurgeNonEmptyOnDrift OPTIONALLY clears them first (a cleaner table) but is NOT required and NEVER blocks.
                $cntRaw = az monitor log-analytics query --workspace $wsCustomerId --analytics-query "$tableName | count" -o json 2>$null
                $rowCnt = if ($LASTEXITCODE -eq 0 -and $cntRaw) { [int](@($cntRaw | ConvertFrom-Json)[0].Count) } else { -1 }
                if ($rowCnt -gt 0 -and -not $PurgeNonEmptyOnDrift) {
                    Write-Host "[Onboard-CategorySurgical] '$tableName' has $rowCnt row(s) + drifts · drop+recreate APPLIES the new schema (proven · no soft-restore of the schema) · the old rows are cosmetic (windowed-out + re-polled fresh) · pass -PurgeNonEmptyOnDrift to clear them first. Proceeding to drop+recreate." -ForegroundColor Yellow
                } elseif ($rowCnt -gt 0) {
                    # OPTIONAL cosmetic pre-clean (NOT required for the schema · the recreate is fresh-typed regardless): empty
                    # the table via a management-plane data PURGE using native Invoke-RestMethod (az.cmd mangles a JSON
                    # --filters arg · the SAME no-mangling fix as Force-XdrFullCycle), polled to completion before the drop so
                    # the old rows do not linger. Authorized destructive op on our own _CL data. NEVER a blocker — if the purge
                    # does not complete in budget we WARN and proceed to the drop anyway (the new schema applies regardless).
                    Write-Host "[Onboard-CategorySurgical] '$tableName' has $rowCnt row(s) · -PurgeNonEmptyOnDrift -> OPTIONAL pre-clean data PURGE (all rows) before the drop ..." -ForegroundColor Yellow
                    $mgmtTok = az account get-access-token --resource https://management.azure.com/ --query accessToken -o tsv 2>$null
                    if (-not $mgmtTok) { throw "[Onboard-CategorySurgical] could not acquire a management-plane token for the purge" }
                    $purgeUri = "https://management.azure.com$pWorkspaceResId/purge?api-version=2020-08-01"
                    $purgeBody = @{ table = $tableName; filters = @(@{ column = 'TimeGenerated'; operator = '>'; value = '2020-01-01T00:00:00Z' }) } | ConvertTo-Json -Depth 6
                    # Capture the purge OPERATION handle (x-ms-status-location header and/or body.operationId). The LA purge
                    # is async; its RELIABLE completion signal is the operation STATUS (status=completed), NOT the row-count
                    # KQL — the count LAGS the actual deletion (live-caught 2026-06-19: count stayed flat at 53,630 for the
                    # whole 20-min budget while the purge was in flight). Poll the operation; keep the count only as a fallback
                    # when no operation handle is returned.
                    $respHdrs = $null; $purgeResp = $null
                    try { $purgeResp = Invoke-RestMethod -Method Post -Uri $purgeUri -Headers @{ Authorization = "Bearer $mgmtTok" } -ContentType 'application/json' -Body $purgeBody -ResponseHeadersVariable respHdrs -TimeoutSec 60 -ErrorAction Stop }
                    catch { throw "[Onboard-CategorySurgical] PURGE submit failed for '$tableName': $($_.Exception.Message)" }
                    $statusUrl = ''
                    if ($respHdrs -and $respHdrs['x-ms-status-location']) { $statusUrl = [string]@($respHdrs['x-ms-status-location'])[0] }
                    if (-not $statusUrl -and $purgeResp -and $purgeResp.PSObject.Properties.Name -contains 'operationId' -and $purgeResp.operationId) {
                        $statusUrl = "https://management.azure.com$pWorkspaceResId/operations/$($purgeResp.operationId)?api-version=2020-08-01"
                    }
                    # The x-ms-status-location header pins api-version=2017-01-01-preview, which Azure no longer registers for
                    # workspaces/operations (live-caught 2026-06-19: GET 404s NoRegisteredProviderFound -> empty status). Normalize
                    # to the supported api-version we POST the purge with, regardless of which source set the URL.
                    if ($statusUrl) { $statusUrl = $statusUrl -replace 'api-version=[^&]+', 'api-version=2020-08-01' }
                    $purged = $false
                    foreach ($pi in 1..120) {   # ~60 min budget @ 30s · the LA purge is async (large tables take longer than 20 min)
                        Start-Sleep -Seconds 30
                        # Re-acquire the management token each poll — over a long (up to 60-min) purge the INITIAL token
                        # EXPIRES (~60-90 min lifetime); an expired token makes the status GET 401 -> empty status -> never
                        # 'completed' (live-caught 2026-06-19: polls 97-120 showed empty status as the token aged out). az
                        # returns a cached still-valid token cheaply, so refreshing every poll is harmless.
                        $mgmtTok = az account get-access-token --resource https://management.azure.com/ --query accessToken -o tsv 2>$null
                        if ($statusUrl) {
                            $st = ''
                            try { $st = [string](Invoke-RestMethod -Method Get -Uri $statusUrl -Headers @{ Authorization = "Bearer $mgmtTok" } -TimeoutSec 60 -ErrorAction Stop).status } catch { $st = '' }
                            Write-Host "[Onboard-CategorySurgical]   purge poll $pi · '$tableName' purge-operation status=$st"
                            if ($st -eq 'completed') { $purged = $true; break }
                        } else {
                            $cRaw = az monitor log-analytics query --workspace $wsCustomerId --analytics-query "$tableName | count" -o json 2>$null
                            $c = if ($LASTEXITCODE -eq 0 -and $cRaw) { [int](@($cRaw | ConvertFrom-Json)[0].Count) } else { -1 }
                            Write-Host "[Onboard-CategorySurgical]   purge poll $pi · '$tableName' count=$c (no operation handle · count-fallback)"
                            if ($c -eq 0) { $purged = $true; break }
                        }
                    }
                    if (-not $purged) { Write-Host "[Onboard-CategorySurgical] '$tableName' OPTIONAL pre-clean purge did not complete in budget (async · still in flight) · PROCEEDING to drop+recreate anyway — the new schema applies regardless and the old rows are windowed-out (cosmetic)." -ForegroundColor Yellow }
                    else { Write-Host "[Onboard-CategorySurgical] '$tableName' purged to 0 · proceeding to drop+recreate fresh-typed." -ForegroundColor Green }
                }
                Write-Host "[Onboard-CategorySurgical] DROPPING '$tableName' so the ARM deploy recreates it FRESH-typed (the new schema applies regardless of prior rows · proven 2026-06-20) ..." -ForegroundColor Yellow
                az monitor log-analytics workspace table delete --resource-group $wsRG --workspace-name $wsName --name $tableName --yes --output none
                if ($LASTEXITCODE -ne 0) { throw "[Onboard-CategorySurgical] table delete FAILED (az exit $LASTEXITCODE) · NOT proceeding" }
                $didRecreateTable = $true   # → the -Apply tail must reset the FA checkpoint so the runtime re-emits into the empty table (BoundaryDeduped-after-recreate fix)
                Write-Host "[Onboard-CategorySurgical] dropped '$tableName' · the ARM deploy recreates it fresh-typed." -ForegroundColor Green
            }
        } else {
            Write-Host "[Onboard-CategorySurgical] live table '$tableName' schema matches target ($($tableCols.Count) target cols) · no recreate needed."
        }
    } else {
        Write-Host "[Onboard-CategorySurgical] table '$tableName' not present yet · ARM will create it fresh."
    }

    # ─── what-if + HARD ASSERT (fail closed on any KeyVault / Web/sites change) ───────────────────
