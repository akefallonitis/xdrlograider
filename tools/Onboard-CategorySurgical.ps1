    # ─── Ensure the per-DCR Monitoring Metrics Publisher role POST-DEPLOY (idempotent · like the appSetting merge) ──
    # Defect-1 fix (WS-card-sync): the role is created with the EXACT SAME deterministic NAME deploy/mainTemplate.json
    # computes via ARM `guid(resourceId('…/dataCollectionRules', dcrName), principalId, 'MMP-DCR-<cat>')`, reproduced
    # offline by Get-XdrArmGuid (Parser · the single-source ARM-guid() reproduction · RFC-4122 v5 / fixed Azure
    # namespace). WHY the explicit name matters: ARM keys roleAssignment idempotency on the assignment NAME. If this
    # surgical onboard let `az role assignment create` mint a RANDOM-GUID name, a later FULL mainTemplate re-deploy
    # (the GA fresh-deploy gate · the failed full-sync) would PUT the role under the guid()-name and 409
    # RoleAssignmentExists against the existing random-named tuple assignment → whole-deployment rollback. Creating it
    # here under the template's guid()-name makes the re-deploy an idempotent SAME-NAME no-op. az role assignment create
    # is still tuple-idempotent (we check the tuple first), so it works for a fresh category AND a re-onboard. WITHOUT
    # this role the FA SAMI cannot publish to the DCR → silent 403 / 0 rows (the P9.5-iii class). SP needs roleAssignments/write.
    $dcrName = az deployment group show --resource-group $ResourceGroup --name $deploymentName --query 'properties.outputs.dcrName.value' -o tsv 2>$null
