    # ─── Post-recreate checkpoint reset (BoundaryDeduped-after-recreate fix · live-caught 2026-06-25) ──
    # A drop+recreate of the table makes it EMPTY, but the FA's exactly-once checkpoint BOUNDARY is unchanged — so on the
    # next poll the runtime sees the rows as already-sent → Entry.Poll.BoundaryDeduped → ZERO rows land in the now-empty
    # recreated table (live-proven: after recreating Defender_ExposureManagement_CL + Defender_EndpointManagement_CL the
    # GetTvmRiskScore/List polls SUCCEEDED but BoundaryDeduped → 0 rows, until a manual Save-XdrCheckpointReset). Fix at
    # source: if we recreated the table this run, AUTO-reset the checkpoint here so the FA re-emits from a clean baseline
    # into the empty table. NON-FATAL — the table/DCR/appSetting already landed; a reset failure WARNS with the manual
    # command and does NOT fail the onboard. -StorageAccount defaults from $env:XDRLR_STORAGE_ACCOUNT; when empty the
    # child tool self-resolves the FA storage account from .env.local (XDRLR_STORAGE_ACCOUNT).
    if ($didRecreateTable) {
        $resetTool = Join-Path $PSScriptRoot 'Save-XdrCheckpointReset.ps1'
        $resetArgs = @('-NoProfile', '-NonInteractive', '-File', $resetTool,
            '-Portal', $Portal, '-Category', $Category, '-ResourceGroup', $ResourceGroup,
            '-Reason', 'schema-change', '-Apply')
        if ($StorageAccount) { $resetArgs += @('-StorageAccount', $StorageAccount) }
        Write-Host ""
        Write-Host "[Onboard-CategorySurgical] table was recreated → Save-XdrCheckpointReset (Reason=schema-change) so the FA re-emits from a clean baseline into the empty table (BoundaryDeduped-after-recreate fix)." -ForegroundColor Yellow
        try {
            & pwsh @resetArgs
            if ($LASTEXITCODE -ne 0) {
                Write-Warning "[Onboard-CategorySurgical] post-recreate Save-XdrCheckpointReset FAILED (NON-FATAL · az exit $LASTEXITCODE) — run it manually: pwsh tools/Save-XdrCheckpointReset.ps1 -Portal $Portal -Category $Category -Reason schema-change -Apply, else the recreated table '$tableName' stays empty (BoundaryDeduped)."
            } else {
                Write-Host "[Onboard-CategorySurgical] checkpoint reset done · the next TimerTrigger re-emits $Portal/$Category from a clean baseline into the empty '$tableName'." -ForegroundColor Green
            }
        } catch {
            Write-Warning "[Onboard-CategorySurgical] post-recreate Save-XdrCheckpointReset FAILED (NON-FATAL) — run it manually: pwsh tools/Save-XdrCheckpointReset.ps1 -Portal $Portal -Category $Category -Reason schema-change -Apply, else the recreated table '$tableName' stays empty (BoundaryDeduped). Error: $($_.Exception.Message)"
        }

        # ─── DCR schema-propagation lag notice (PROPAGATION-PENDING · live-caught this session) ──────────────
        # When the recreate ADDED ≥1 NEW column, Azure's propagation of the recreated table's schema to the DCR/DCE
        # INGESTION endpoint lags ~10-15 min. So the FIRST re-emit after the checkpoint reset above can land the NEW
        # column(s) EMPTY while every PRE-EXISTING column + id flow normally (live-proven: a MachineSecurityStates re-poll
