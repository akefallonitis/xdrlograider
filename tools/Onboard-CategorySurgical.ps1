# ─── Pure what-if safety predicate (extracted · unit-tested via the dot-source seam below) ─────────
function Test-XdrChangeTouchesFoundation {
    <#
      Returns $true iff a single `az deployment group what-if` change entry would MUTATE a FOUNDATION resource
      (Microsoft.KeyVault/* or Microsoft.Web/sites) — the surgical add must NEVER do this (fail closed).
      · NoChange / Ignore        -> $false (no mutation).
      · Create / Modify / Delete -> $true iff the TARGET resourceId's /providers/<type> segment is forbidden.
      · Unsupported              -> what-if could not evaluate the change. This arises ONLY for a resource whose
        identity depends on a runtime reference() (here exclusively the per-DCR role · guid seeded by
        reference(FA).principalId). A KV/Web mutation has a STATIC identity and is always evaluable, never Unsupported.
        The role's raw resourceId expression INCIDENTALLY contains the FA id inside reference() (a READ of principalId,
        NOT a change) so a naive substring scan false-trips. Allow ONLY the per-DCR roleAssignment; fail closed on any
        OTHER opaque change.
    #>
    [OutputType([bool])]
    param([string] $ChangeType, [string] $ResId)
    if ($ChangeType -in @('NoChange', 'Ignore')) { return $false }
    if ($ChangeType -eq 'Unsupported') {
        if ($ResId -match 'Microsoft\.Authorization/roleAssignments' -and $ResId -match 'dataCollectionRules') { return $false }
        return $true   # unknown opaque change · fail closed
    }
    return ($ResId -match [regex]::Escape('/providers/Microsoft.KeyVault/') -or $ResId -match [regex]::Escape('/providers/Microsoft.Web/sites'))
}

# ─── Pure table-schema-drift predicate (extracted · unit-tested via the dot-source seam below) ─────
function Test-XdrTableColumnDrift {
    <#
      Returns the list of TARGET columns whose (name→type) is MISSING-from or MISTYPED-vs the LIVE table schema.
      A non-empty result means an in-place ARM PUT would NOT reliably apply the schema: LA cannot change an existing
      column's type (string→boolean is rejected outright · the table keeps string while the DCR stream becomes
      boolean → a mismatch the ingestion path silently DROPS) and an in-place column ADD leaves the ingestion schema
      stale (new rows drop the added col) — both live-caught 2026-06-17 (Operations typed cols green-but-null). The
      ONLY reliable fix is DROP+RECREATE (fresh ingest+query schema · how cat-1 Exposure got its working typed cols).
      Name compared case-insensitively (hashtable default); type normalized lower-invariant (LA 'dateTime' ==
      artifact 'datetime'). Extra LIVE columns (LA-managed TimeGenerated/TenantId/Type/_ResourceId) are IGNORED —
      only the TARGET columns must land, so drift is one-directional (target ⊄ live).
    #>
    [OutputType([string[]])]
    param([object[]] $TargetCols, [object[]] $LiveCols)
    $liveMap = @{}
    foreach ($lc in @($LiveCols)) { if ($lc -and $lc.name) { $liveMap[[string]$lc.name] = (Get-XdrCanonicalColType ([string]$lc.type)) } }
    $drift = [System.Collections.Generic.List[string]]::new()
    foreach ($tc in @($TargetCols)) {
        if (-not $tc -or -not $tc.name) { continue }
        $tn = [string]$tc.name
        $tt = Get-XdrCanonicalColType ([string]$tc.type)
        if (-not $liveMap.ContainsKey($tn)) { $drift.Add("ADD $tn ($tt)"); continue }
        if ($liveMap[$tn] -ne $tt) { $drift.Add("RETYPE $tn ($($liveMap[$tn])->$tt)") }
    }
    return $drift.ToArray()
}

# Canonical column-type normalizer · ARM/artifact names (boolean,dateTime,int) vs KQL getschema names (bool,datetime,long).
# Map both to a canonical form so 'boolean'=='bool' and 'dateTime'=='datetime' are NOT read as false drift; int folds
# into long (LA stores int32 as long effectively · harmless widening). Used by Test-XdrTableColumnDrift to compare the
# artifact's target types against the table's EFFECTIVE (getschema) types.
function Get-XdrCanonicalColType {
    [OutputType([string])]
    param([string] $Type)
    switch (([string]$Type).Trim().ToLowerInvariant()) {
        'boolean' { 'bool' }
        'int'     { 'long' }
        'int32'   { 'long' }
        'int64'   { 'long' }
        'date'    { 'datetime' }
        default   { ([string]$Type).Trim().ToLowerInvariant() }
    }
}

