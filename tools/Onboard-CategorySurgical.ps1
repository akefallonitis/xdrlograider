    }

    Write-Host ""
    Write-Host "[Onboard-CategorySurgical] what-if change summary:"
    foreach ($c in $changes) {
        $rid = if ($c.PSObject.Properties['resourceId']) { $c.resourceId } else { '<id-in-after/before>' }
        Write-Host ("   {0,-8} {1}" -f ([string]$c.changeType), $rid)
    }

    if ($offending.Count -gt 0) {
        Write-Host ""
        Write-Host "[Onboard-CategorySurgical] HARD-ASSERT FAILED · what-if would touch FOUNDATION resources (forbidden):" -ForegroundColor Red
        $offending | ForEach-Object { Write-Host "   ! $_" -ForegroundColor Red }
        throw "[Onboard-CategorySurgical] FAIL CLOSED · surgical add must NOT change any Microsoft.KeyVault/* or Microsoft.Web/sites resource · refusing to apply"
    }
