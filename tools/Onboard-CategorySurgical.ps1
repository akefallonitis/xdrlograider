#Requires -Version 7.4
<#
.SYNOPSIS
LIVE incremental · surgically onboard ONE new Defender category (table + DCR + FA appSetting + per-DCR role +
connector-card sync) to an ALREADY-DEPLOYED XdrLogRaider stack · WITHOUT touching the foundation (Key Vault ·
Function App · Storage).

.DESCRIPTION
This is the live counterpart to dev-tools/Build-MainTemplate.ps1 (which assembles the full marketplace template
for a fresh one-click deploy). Onboard-CategorySurgical adds Category #2..N to an existing RG incrementally:

  1. Build a MINIMAL standalone ARM template from deploy/per-category-schemas/<Portal>-<Category>.json containing
     ONLY the per-category resources — NOTHING from the foundation:
        (a) cross-RG NESTED table deployment  (resourceGroup-only · NO subscriptionId · scope=inner)
        (b) TOP-LEVEL DCR                      (streamDeclarations from the artifact · dependsOn nested simple-name)
     The per-DCR Monitoring Metrics Publisher role (FA SAMI → the new DCR) is ensured POST-DEPLOY via az
     check-then-create (idempotent · an ARM roleAssignment PUT 409s RoleAssignmentExists on re-onboard), next to the appSetting merge.
     The minimal template recomputes the SAME deterministic resource names as mainTemplate (namePrefix/suffix from
     deploymentNameSuffix · workspace coords from workspaceResourceId) so the new DCR/table/role bind to the live stack.
     The FA appSetting XDRLR_DCR_<PORTAL>_<CATEGORY> is NOT in the ARM template — it is MERGED post-deploy via
     `az functionapp config appsettings set` (which merges · ARM PUT on siteConfig.appSettings would REPLACE them all
     and force a Microsoft.Web/sites change · which this tool forbids).

  2. Run `az deployment group what-if` on the minimal template and HARD-ASSERT the change set contains
        0 × Microsoft.KeyVault/*   AND   0 × Microsoft.Web/sites
     (Create/Modify/Delete/Deploy). FAIL CLOSED if it would touch either — the whole point is to never risk the
     KeyVault secrets or bounce/replace the Function App during a category add.

  3. Only with -Apply: `az deployment group create --mode Incremental` (SYNCHRONOUS · no --no-wait), then
     `az functionapp config appsettings set` (merge the XDRLR_DCR_<PORTAL>_<CATEGORY> appSetting) + `az role assignment`
     check-then-create (ensure the FA SAMI's per-DCR Monitoring Metrics Publisher role · idempotent).

Discipline (memory · plan §11.1): NO `--no-wait` on any op · NO bare `--force` · NEVER az group delete. Default is
PLAN-ONLY (what-if + assertion). Applying requires the explicit -Apply switch.

.PARAMETER Portal
e.g. 'Defender'.

.PARAMETER Category
e.g. 'Alerts' · 'Incidents'. Case-sensitive · matches the artifact / manifest Category.

.PARAMETER ResourceGroup
The connector RG of the already-deployed stack (e.g. 'xdrlograider'). If omitted, falls back to env
XDRLR_TARGET_RG then XDRLR_CONNECTOR_RG.

.PARAMETER ParametersFile
ARM parameters file matching the original deploy (default repo parameters.local.json). Supplies location +
deploymentNameSuffix + workspaceResourceId so names align with the live stack.

.PARAMETER Apply
Actually deploy (what-if assertion must pass first). Default OFF = plan-only.

.PARAMETER SchemaArtifactPath
Override the per-category-schema artifact path (default deploy/per-category-schemas/<Portal>-<Category>.json).

.PARAMETER EmitTemplateOnly
Dry-run · assemble + parse-validate the minimal template, write it to a temp file, emit that path to stdout and
STOP — no az CLI, no what-if, no deploy. Used by the GM-2 surgical-output self-test (assert the emitted DCR dataFlow
carries the artifact's transformKql, not a hardcode) and for offline template inspection.

.PARAMETER SkipConnectorCardSync
After a successful -Apply, suppress the post-add Sentinel connector-card sync (Defect-3). By default the onboard
deploys deploy/connector-card-only.json (the SINGLE dataConnectorDefinition · all shipped categories) to the workspace
RG so the Data Connectors gallery card never lags the onboarded categories. The card-only deploy touches NO foundation
resource (no FA zip reset · no roles). Card-sync failure is NON-FATAL (the category data already landed); set this to
skip it entirely (e.g. when syncing the card out-of-band).

.PARAMETER ConnectorCardTemplate
Path to the targeted card-only ARM template (default deploy/connector-card-only.json · regenerated by
dev-tools/Build-MainTemplate.ps1 from the same card content as mainTemplate). Deployed standalone to the workspace RG.

.PARAMETER ConnectorDefinitionName
The Sentinel connector definition name (default 'XdrLogRaiderDefenderXdr') · MUST match the value the foundation
deploy used (mainTemplate variables.connectorDefinitionName) so the card sync UPDATES the same card, not a new one.

.PARAMETER RecreateTableOnSchemaDrift
When the live workspace table's schema DRIFTS from the target artifact (a column whose TYPE changed — e.g. a
string→boolean re-type — or a newly-ADDED column), DROP+RECREATE the table so the deploy creates it FRESH. An
in-place ARM PUT updates LA's query-time schema (getschema shows the new type) but NOT the ingestion path, so new
rows silently DROP the changed/added columns (live-caught 2026-06-17 · Operations typed cols green-but-null). A
fresh table — how cat-1 Exposure got its working typed cols — has a consistent ingest+query schema. DESTRUCTIVE:
drops existing rows in the table (re-poll repopulates · purge-then-reingest re-baseline). Default OFF = FAIL CLOSED
with a clear message when drift is detected (never silently in-place-modify a typed column into a stale schema).

.PARAMETER PurgeNonEmptyOnDrift
OPTIONAL companion to -RecreateTableOnSchemaDrift (NOT required): a drop+recreate of a NON-EMPTY table already applies
the new schema fresh-typed (live-proven 2026-06-20 — a populated 50-col table recreated to the full 65-col target, NO
soft-restore of the schema), so the recreate proceeds with OR without this flag. When SET, it FIRST runs a management-
plane data PURGE (async · polled to completion) so the old rows do not linger as soft-restored pre-deploy clutter —
purely COSMETIC (the windowed verifier already excludes pre-deploy rows + the next poll re-emits fresh-typed). NON-
BLOCKING: an incomplete purge WARNS and proceeds to the drop anyway. DESTRUCTIVE on our own _CL data only (authorized ·
never an RG/unrelated deletion). Default OFF = drop+recreate directly (no purge · the old rows are cosmetic).

.OUTPUTS
Exit 0 · what-if clean (and applied if -Apply) · non-zero · assertion failed / az error / bad inputs.
#>
