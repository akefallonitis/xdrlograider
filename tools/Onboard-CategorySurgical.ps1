        # The first guid() arg is the DCR's ARM resourceId STRING — which inside the role's same-RG (connector RG) nested
        # deployment is exactly $dcrId computed above (/subscriptions/.../dataCollectionRules/<dcrName>).
        $roleAssignmentName = Get-XdrArmGuid -Arguments @($dcrId, $faPid, "MMP-DCR-$catLower")
        Write-Host "[Onboard-CategorySurgical] deterministic per-DCR role name (== mainTemplate guid()) : $roleAssignmentName"
